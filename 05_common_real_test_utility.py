def safe_json(value: Any) -> str:
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            default=str,
        )
    except Exception:
        return str(value)


def normalize_name(value: Any) -> str:
    return "".join(
        char
        for char in str(value).strip().lower()
        if char.isalnum()
    )


