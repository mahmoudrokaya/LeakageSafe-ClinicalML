def sidecar_candidates(
    table_path: Path,
) -> List[Path]:
    candidates = [
        Path(
            str(table_path)
            + ".provenance.json"
        ),

        table_path.with_name(
            table_path.stem
            + "_provenance.json"
        ),

        table_path.with_suffix(
            ".json"
        ),
    ]

    unique = []

    seen = set()

    for candidate in candidates:
        key = str(
            candidate
        ).lower()

        if key not in seen:
            seen.add(key)
            unique.append(
                candidate
            )

    return unique


def read_json_file(
    path: Path,
) -> Optional[Dict[str, Any]]:
    try:
        with path.open(
            "r",
            encoding="utf-8",
        ) as handle:
            obj = json.load(handle)

        if isinstance(
            obj,
            dict,
        ):
            return obj

    except Exception:
        return None

    return None


def get_first_field(
    obj: Dict[str, Any],
    candidates: Sequence[str],
) -> Tuple[
    Optional[Any],
    Optional[str],
]:
    normalized = {
        normalize_name(key):
            key
        for key in obj.keys()
    }

    for candidate in candidates:
        if candidate in obj:
            return (
                obj[candidate],
                candidate,
            )

        key = normalize_name(
            candidate
        )

        if key in normalized:
            actual = normalized[
                key
            ]

            return (
                obj[actual],
                actual,
            )

    return (
        None,
        None,
    )


