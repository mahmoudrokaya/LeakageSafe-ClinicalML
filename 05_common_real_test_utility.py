def evaluate_training_condition(
    condition_name: str,
    training_source: str,
    X_train_processed: np.ndarray,
    y_train: np.ndarray,
    X_test_processed: np.ndarray,
    y_test: np.ndarray,
    test_source_indices: np.ndarray,
    classifier_template,
) -> Tuple[
    Dict[str, Any],
    Dict[str, Any],
    List[Dict[str, Any]],
]:
    model = train_classifier(
        classifier_template,
        X_train_processed,
        y_train,
    )

    y_pred = np.asarray(
        model.predict(
            X_test_processed
        ),
        dtype=int,
    )

    y_score, score_source = get_positive_score(
        model,
        X_test_processed,
    )

    metrics, confusion = compute_metrics(
        y_test,
        y_pred,
        y_score,
    )

    metric_row = {
        "condition":
            condition_name,

        "training_source":
            training_source,

        "n_training":
            len(y_train),

        "n_common_real_test":
            len(y_test),

        **metrics,
    }

    confusion_row = {
        "condition":
            condition_name,

        "training_source":
            training_source,

        **confusion,
    }

    prediction_rows = []

    for position in range(
        len(y_test)
    ):
        prediction_rows.append(
            {
                "condition":
                    condition_name,

                "training_source":
                    training_source,

                "common_test_position":
                    position,

                "original_source_row_index":
                    int(
                        test_source_indices[
                            position
                        ]
                    ),

                "y_true":
                    int(
                        y_test[
                            position
                        ]
                    ),

                "y_pred":
                    int(
                        y_pred[
                            position
                        ]
                    ),

                "correct":
                    int(
                        y_true_equal(
                            y_test[position],
                            y_pred[position],
                        )
                    ),

                "y_score_positive":
                    float(
                        y_score[
                            position
                        ]
                    ),

                "score_source":
                    score_source,
            }
        )

    return (
        metric_row,
        confusion_row,
        prediction_rows,
    )


def y_true_equal(
    y_true: Any,
    y_pred: Any,
) -> bool:
    return int(
        y_true
    ) == int(
        y_pred
    )


