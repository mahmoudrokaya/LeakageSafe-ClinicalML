def map_features(
    df: pd.DataFrame,
    feature_names: List[str],
) -> Tuple[
    Optional[pd.DataFrame],
    Dict[str, Any],
]:
    lookup = {}

    duplicates = set()

    for column in df.columns:
        key = normalize_name(
            column
        )

        if key in lookup:
            duplicates.add(key)

        lookup[
            key
        ] = column

    mapped = {}
    missing = []
    ambiguous = []

    for feature in feature_names:
        if feature in df.columns:
            mapped[
                feature
            ] = df[
                feature
            ]
            continue

        key = normalize_name(
            feature
        )

        if key in duplicates:
            ambiguous.append(
                feature
            )
            continue

        if key not in lookup:
            missing.append(
                feature
            )
            continue

        mapped[
            feature
        ] = df[
            lookup[key]
        ]

    diagnostics = {
        "required_features":
            len(feature_names),

        "matched_features":
            len(mapped),

        "missing_features":
            missing,

        "ambiguous_features":
            ambiguous,
    }

    if missing or ambiguous:
        return (
            None,
            diagnostics,
        )

    return (
        pd.DataFrame(mapped),
        diagnostics,
    )


def numeric_dataframe(
    df: pd.DataFrame,
) -> pd.DataFrame:
    result = pd.DataFrame(
        index=df.index
    )

    for column in df.columns:
        result[
            column
        ] = pd.to_numeric(
            df[column],
            errors="coerce",
        )

    return result


def normalize_binary_target(
    series: pd.Series,
) -> pd.Series:
    numeric = pd.to_numeric(
        series,
        errors="coerce",
    )

    if numeric.notna().all():
        unique = sorted(
            numeric.unique()
        )

        if set(unique).issubset(
            {0, 1}
        ):
            return numeric.astype(int)

    mapping = {
        "recovered": 0,
        "survived": 0,
        "survivor": 0,
        "alive": 0,
        "death": 1,
        "dead": 1,
        "deceased": 1,
        "killed": 1,
    }

    converted = (
        series
        .astype(str)
        .str.strip()
        .str.lower()
        .map(mapping)
    )

    if converted.isna().any():
        raise RuntimeError(
            "Target cannot be normalized safely to {0,1}."
        )

    return converted.astype(int)


