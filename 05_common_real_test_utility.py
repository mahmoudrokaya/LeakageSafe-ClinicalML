def get_positive_score(
    model,
    X: np.ndarray,
) -> Tuple[
    np.ndarray,
    str,
]:
    if hasattr(
        model,
        "predict_proba",
    ):
        probabilities = model.predict_proba(
            X
        )

        classes = list(
            model.classes_
        )

        if 1 not in classes:
            raise RuntimeError(
                "Positive class 1 absent from classifier classes_."
            )

        positive_index = classes.index(
            1
        )

        return (
            np.asarray(
                probabilities[
                    :,
                    positive_index
                ],
                dtype=float,
            ),
            "predict_proba_positive_class",
        )

    if hasattr(
        model,
        "decision_function",
    ):
        score = np.asarray(
            model.decision_function(
                X
            ),
            dtype=float,
        )

        return (
            score,
            "decision_function",
        )

    raise RuntimeError(
        "Classifier has neither predict_proba nor decision_function."
    )


def compute_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    y_score: np.ndarray,
) -> Tuple[
    Dict[str, Any],
    Dict[str, Any],
]:
    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=[
            0,
            1,
        ],
    )

    tn, fp, fn, tp = cm.ravel()

    specificity = (
        tn / (
            tn + fp
        )
        if (
            tn + fp
        ) > 0
        else np.nan
    )

    metrics = {
        "accuracy":
            accuracy_score(
                y_true,
                y_pred,
            ),

        "precision":
            precision_score(
                y_true,
                y_pred,
                zero_division=0,
            ),

        "recall_sensitivity":
            recall_score(
                y_true,
                y_pred,
                zero_division=0,
            ),

        "specificity":
            specificity,

        "f1":
            f1_score(
                y_true,
                y_pred,
                zero_division=0,
            ),

        "roc_auc":
            roc_auc_score(
                y_true,
                y_score,
            ),
    }

    confusion = {
        "tn":
            int(tn),

        "fp":
            int(fp),

        "fn":
            int(fn),

        "tp":
            int(tp),

        "total":
            int(
                tn
                + fp
                + fn
                + tp
            ),
    }

    return (
        metrics,
        confusion,
    )


