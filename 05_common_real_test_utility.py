def make_locked_split(
    raw_df: pd.DataFrame,
    target_col: str,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    pd.Series,
]:
    y = normalize_binary_target(
        raw_df[target_col]
    )

    source_indices = np.arange(
        len(raw_df),
        dtype=int,
    )

    train_idx, test_idx = train_test_split(
        source_indices,
        test_size=LOCKED_TEST_SIZE,
        random_state=LOCKED_SPLIT_SEED,
        stratify=y.to_numpy(),
    )

    train_idx = np.asarray(
        train_idx,
        dtype=int,
    )

    test_idx = np.asarray(
        test_idx,
        dtype=int,
    )

    return (
        train_idx,
        test_idx,
        y,
    )


def verify_split_integrity(
    train_idx: np.ndarray,
    test_idx: np.ndarray,
    total_rows: int,
) -> List[Dict[str, Any]]:
    overlap = set(
        train_idx.tolist()
    ) & set(
        test_idx.tolist()
    )

    combined = list(
        train_idx
    ) + list(
        test_idx
    )

    rows = [
        {
            "check":
                "train_test_index_overlap",

            "value":
                len(overlap),

            "expected":
                0,

            "status":
                (
                    "PASS"
                    if len(overlap) == 0
                    else "FAIL"
                ),
        },
        {
            "check":
                "combined_index_count",

            "value":
                len(combined),

            "expected":
                total_rows,

            "status":
                (
                    "PASS"
                    if len(combined)
                    == total_rows
                    else "FAIL"
                ),
        },
        {
            "check":
                "unique_combined_index_count",

            "value":
                len(
                    set(combined)
                ),

            "expected":
                total_rows,

            "status":
                (
                    "PASS"
                    if len(
                        set(combined)
                    )
                    == total_rows
                    else "FAIL"
                ),
        },
    ]

    return rows


