def fit_training_preprocessor(
    X_train: pd.DataFrame,
) -> Tuple[
    np.ndarray,
    SimpleImputer,
    MinMaxScaler,
    StandardScaler,
    List[Dict[str, Any]],
]:
    imputer = SimpleImputer(
        strategy="median"
    )

    minmax = MinMaxScaler()

    standard = StandardScaler()

    X_imputed = imputer.fit_transform(
        X_train
    )

    X_minmax = minmax.fit_transform(
        X_imputed
    )

    X_final = standard.fit_transform(
        X_minmax
    )

    audit = []

    for index, feature in enumerate(
        X_train.columns
    ):
        audit.append(
            {
                "feature":
                    feature,

                "missing_in_locked_train":
                    int(
                        X_train[
                            feature
                        ].isna().sum()
                    ),

                "imputation_median":
                    float(
                        imputer.statistics_[
                            index
                        ]
                    ),

                "minmax_data_min":
                    float(
                        minmax.data_min_[
                            index
                        ]
                    ),

                "minmax_data_max":
                    float(
                        minmax.data_max_[
                            index
                        ]
                    ),

                "standard_mean":
                    float(
                        standard.mean_[
                            index
                        ]
                    ),

                "standard_scale":
                    float(
                        standard.scale_[
                            index
                        ]
                    ),

                "fit_scope":
                    "LOCKED_REAL_TRAIN_ONLY",
            }
        )

    return (
        X_final,
        imputer,
        minmax,
        standard,
        audit,
    )


def apply_training_preprocessor(
    X: pd.DataFrame,
    imputer: SimpleImputer,
    minmax: MinMaxScaler,
    standard: StandardScaler,
) -> np.ndarray:
    X_imputed = imputer.transform(
        X
    )

    X_minmax = minmax.transform(
        X_imputed
    )

    return standard.transform(
        X_minmax
    )


