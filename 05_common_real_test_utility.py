def sha256_file(path: Path) -> str:
    h = hashlib.sha256()

    with path.open("rb") as handle:
        while True:
            block = handle.read(
                1024 * 1024
            )

            if not block:
                break

            h.update(block)

    return h.hexdigest()


def sha256_integer_sequence(
    values: Sequence[int],
) -> str:
    """
    Stable SHA256 of ordered integer indices.
    """

    payload = ",".join(
        str(int(value))
        for value in values
    ).encode("utf-8")

    return hashlib.sha256(
        payload
    ).hexdigest()


def write_csv(
    path: Path,
    rows: Sequence[Dict[str, Any]],
    columns: Optional[List[str]] = None,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if not rows:
        pd.DataFrame(
            columns=columns or []
        ).to_csv(
            path,
            index=False,
            encoding="utf-8-sig",
        )
        return

    df = pd.DataFrame(rows)

    if columns:
        remainder = [
            column
            for column in df.columns
            if column not in columns
        ]

        df = df[
            columns + remainder
        ]

    df.to_csv(
        path,
        index=False,
        encoding="utf-8-sig",
    )


def read_csv_robust(
    path: Path,
) -> pd.DataFrame:
    separator = (
        "\t"
        if path.suffix.lower() == ".tsv"
        else ","
    )

    errors = []

    for encoding in [
        "utf-8-sig",
        "utf-8",
        "cp1252",
        "latin-1",
    ]:
        try:
            return pd.read_csv(
                path,
                encoding=encoding,
                sep=separator,
            )

        except Exception as exc:
            errors.append(
                f"{encoding}: {repr(exc)}"
            )

    raise RuntimeError(
        f"Cannot read table:\n{path}\n"
        + "\n".join(errors)
    )


def read_table(
    path: Path,
) -> Optional[pd.DataFrame]:
    suffix = path.suffix.lower()

    try:
        if suffix in {
            ".csv",
            ".tsv",
        }:
            return read_csv_robust(path)

        if suffix in {
            ".xlsx",
            ".xls",
        }:
            return pd.read_excel(path)

        if suffix == ".parquet":
            return pd.read_parquet(path)

    except Exception:
        return None

    return None


