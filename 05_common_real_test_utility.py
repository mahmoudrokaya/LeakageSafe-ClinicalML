def audit_synthetic_provenance(
    synthetic_candidates: Dict[
        str,
        Dict[str, Any],
    ],
    train_indices_hash: str,
) -> Tuple[
    List[Dict[str, Any]],
    List[Dict[str, Any]],
]:
    audit_rows = []

    admissible = []

    for relative, candidate in synthetic_candidates.items():
        table_path = candidate[
            "path"
        ]

        sidecars = [
            path
            for path
            in sidecar_candidates(
                table_path
            )
            if path.exists()
        ]

        if not sidecars:
            audit_rows.append(
                {
                    "synthetic_table":
                        relative,

                    "sidecar":
                        "",

                    "generated_from_training_only":
                        False,

                    "test_rows_excluded":
                        False,

                    "split_seed_verified":
                        False,

                    "training_indices_hash_verified":
                        False,

                    "overall_admissible":
                        False,

                    "status":
                        "NO_PROVENANCE_SIDECAR",
                }
            )

            continue

        any_admissible = False

        for sidecar_path in sidecars:
            provenance = read_json_file(
                sidecar_path
            )

            if provenance is None:
                audit_rows.append(
                    {
                        "synthetic_table":
                            relative,

                        "sidecar":
                            relative_path(
                                sidecar_path
                            ),

                        "generated_from_training_only":
                            False,

                        "test_rows_excluded":
                            False,

                        "split_seed_verified":
                            False,

                        "training_indices_hash_verified":
                            False,

                        "overall_admissible":
                            False,

                        "status":
                            "UNREADABLE_OR_NONOBJECT_JSON",
                    }
                )

                continue

            train_only_value, train_only_field = (
                get_first_field(
                    provenance,
                    [
                        "generated_from_training_only"
                    ],
                )
            )

            test_excluded_value, test_excluded_field = (
                get_first_field(
                    provenance,
                    [
                        "test_rows_excluded"
                    ],
                )
            )

            seed_value, seed_field = (
                get_first_field(
                    provenance,
                    EXPECTED_PROVENANCE_SPLIT_SEED_FIELDS,
                )
            )

            hash_value, hash_field = (
                get_first_field(
                    provenance,
                    EXPECTED_PROVENANCE_TRAIN_HASH_FIELDS,
                )
            )

            generated_train_only = (
                train_only_value is True
            )

            test_rows_excluded = (
                test_excluded_value is True
            )

            try:
                seed_verified = (
                    int(seed_value)
                    ==
                    LOCKED_SPLIT_SEED
                )
            except Exception:
                seed_verified = False

            hash_verified = (
                isinstance(
                    hash_value,
                    str,
                )
                and
                hash_value.strip().lower()
                ==
                train_indices_hash.lower()
            )

            overall = all(
                [
                    generated_train_only,
                    test_rows_excluded,
                    seed_verified,
                    hash_verified,
                ]
            )

            audit_rows.append(
                {
                    "synthetic_table":
                        relative,

                    "sidecar":
                        relative_path(
                            sidecar_path
                        ),

                    "generated_from_training_only":
                        generated_train_only,

                    "generated_from_training_only_field":
                        train_only_field or "",

                    "test_rows_excluded":
                        test_rows_excluded,

                    "test_rows_excluded_field":
                        test_excluded_field or "",

                    "split_seed":
                        seed_value,

                    "split_seed_field":
                        seed_field or "",

                    "split_seed_verified":
                        seed_verified,

                    "training_indices_sha256":
                        hash_value,

                    "training_indices_hash_field":
                        hash_field or "",

                    "expected_training_indices_sha256":
                        train_indices_hash,

                    "training_indices_hash_verified":
                        hash_verified,

                    "overall_admissible":
                        overall,

                    "status":
                        (
                            "PASS"
                            if overall
                            else "FAIL"
                        ),
                }
            )

            if overall:
                any_admissible = True

                admissible.append(
                    {
                        "synthetic_table":
                            relative,

                        "sidecar":
                            relative_path(
                                sidecar_path
                            ),

                        "table_sha256":
                            sha256_file(
                                table_path
                            ),

                        "training_indices_sha256":
                            train_indices_hash,

                        "status":
                            "ADMISSIBLE",
                    }
                )

                break

        if not any_admissible:
            pass

    return (
        audit_rows,
        admissible,
    )


